export const getSortedParkItems = (
    items: ParkItem[],
    paradeFirst: boolean 
  ): ParkItem[] => {
    const isInactive = (time: string) =>
      ['점검중', '중간점검', '정기휴연', '', '없음'].includes(time);
  
    const parseTime = (time: string) => {
      if (isInactive(time)) return Infinity;
      const match = time.match(/\d+/);
      return match ? parseInt(match[0], 10) : Infinity;
    };
  
    const LEVEL_ORDER: ParkLevel[] = ['B1', '1F', null, '2F', '3F', '4F'];
    const getLevelOrder = (level: ParkLevel) => {
      const index = LEVEL_ORDER.indexOf(level);
      return index === -1 ? LEVEL_ORDER.length : index;
    };
    const getAreaOrder = (area: ParkArea) => (area === '실내' ? 0 : 1);
  
    const parades = items
      .filter((i) => i.category === '퍼레이드')
      .sort((a, b) => parseTime(a.time) - parseTime(b.time));
  
    const attractions = items
      .filter((i) => i.category === '어트랙션')
      .sort((a, b) => parseTime(a.time) - parseTime(b.time));
  
    const others = items
      .filter((i) => i.category === '레스토랑' || i.category === '편의시설')
      .sort((a, b) => {
        const levelDiff = getLevelOrder(a.level) - getLevelOrder(b.level);
        if (levelDiff !== 0) return levelDiff;
        return getAreaOrder(a.area) - getAreaOrder(b.area);
      });
  
    return paradeFirst ? [...parades, ...attractions, ...others] : [...attractions, ...others, ...parades];
  };